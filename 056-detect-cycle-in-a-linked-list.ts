//
// Given the head of a linked list, determine if the linked list has a cycle in it.
//
// A cycle exists if a node can be reached again by continuously following the next pointer.
//
// Example:
//
// Input: head = [3,2,0,-4], pos = 1
// Output: true
// Explanation: There is a cycle where the tail connects to the node at index 1.
// Input: head = [1,2], pos = -1
// Output: false
// Explanation: There is no cycle.
//
// Constraints:
//
// The number of nodes is in the range [0, 10^4]
// -10^5 <= Node.val <= 10^5
//
// Follow-up:
//
// Can you solve it using O(1) memory? (Hint: Floyd’s Cycle Detection)
//
